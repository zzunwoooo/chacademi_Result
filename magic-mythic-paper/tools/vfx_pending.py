def params(line):
    m = re.match(r'(\w+)\{([^}]*)\}', line)
    if not m: return None, {}
    out = {}
    for kv in m.group(2).split(';'):
        if '=' in kv: k, v = kv.split('=', 1); out[k] = v
    return m.group(1), out

def gameplay_events(lines):
    ev = []
    for l in lines:
        mech, p = params(l)
        if mech is None: continue
        if mech == 'chahit': ev.append(p.get('hitevent', 'external:hit').split(':', 1)[1])
        elif mech == 'chabolt': ev += [p.get('hitevent', 'external:contact').split(':', 1)[1], p.get('missevent', 'external:block_contact').split(':', 1)[1]]
        elif mech == 'chazone': ev += ['strike'] + (['hit'] if p.get('solid') == 'true' else [])
        elif mech == 'chachannel': ev += ['laser_fire', 'struct_cancel']
        else: ev += EVENTS.get((mech, p.get('type', '')), [])
    seen = []
    for e in ev:
        if e not in seen: seen.append(e)
    return ['external:' + e for e in seen]

def main():
    systems = json.load(open(os.path.join(REPO, 'portable-vfx-runtime/docs/pending/vfx-101-167-systems.json'), encoding='utf-8'))
    spec = {s[0]: s for s in spells.S}
    lines = ['# DRAFT - not loaded. Generated by magic-mythic-paper/tools/vfx_pending.py. See that file for why and how to merge.',
             'schema-version: 1', 'bindings:']
    for sid, v in sorted(systems.items(), key=lambda kv: kv[1]['number']):
        folder = v['folder']; base = folder.lower()
        sys_ = v['systems']
        has_proj = any(s['role'] == 'projectile' for s in sys_)
        sustain = v.get('sustainStart')
        begin_ids = [s['id'] for s in sys_ if s['phase'] in ('begin', 'sustain')]
        rng = spec[sid][3] if sid in spec else 15
        lines += [f'  {sid}:', f'    folder: {folder}', f'    number: {v["number"]}', f'    schema: "{v["schema"]}"', f'    range: {rng}',
                  f'    client-compatible: true', f'    texture-rgba-mib: {v.get("rgbaMiB")}',
                  '    phases:']
        first_done = False
        for s in sys_:
            role, phase = s['role'], s['phase']
            delay = 0; stop = []
            if role == 'projectile': trig, anchor = 'cast', 'projectile'
            elif role == 'impact': trig, anchor = ('impact' if has_proj else f'external:{s["id"]}'), 'impact'
            elif phase == 'sustain': trig, anchor = 'cast', 'caster'; delay = round((sustain or 0) * 20)
            elif phase == 'end':
                trig, anchor = ('external:trigger' if s.get('endBranch') == 'trigger' else 'expire'), 'caster'; stop = [f'claude:{base}/{i}' for i in begin_ids]
            elif not first_done and phase in ('begin', 'main'): trig, anchor = 'cast', 'caster'
            else: trig, anchor = f'external:{s["id"]}', ('caster' if role == 'attached' else 'impact')
            if role in ('attached', 'link') and anchor == 'impact': anchor = 'target'
            if trig == 'cast' and role != 'projectile': first_done = True
            lines += [f'    - role: {role}', f'      trigger: {trig}', f'      effect: claude:{base}/{s["id"].lower()}', f'      anchor: {anchor}',
                      f'      delay-ticks: {delay}', f'      duration-ticks: {s["ticks"]}']
            if stop: lines.append('      stop-effects: [' + ', '.join(stop) + ']')
        ev = gameplay_events(spec[sid][7]) if sid in spec else []
        lines.append('    gameplay-events: [' + ', '.join(ev) + ']')
        lines.append('    review: draft; confirm triggers/anchors against the bundle NOTES.md before merging')
    out = os.path.join(REPO, 'portable-vfx-runtime/docs/pending/spell-bindings-101-167.yml')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print(len(systems), 'draft bindings ->', out)

if __name__ == '__main__':
    main()
